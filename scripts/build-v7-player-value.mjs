import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildPlayerValueArtifact, buildPlayerValueOutput, loadResearchData, writeJson } from './v7-intelligence-core.mjs';

const data = await loadResearchData({ includePlayers: true });
const output = buildPlayerValueOutput(data);
const artifact = buildPlayerValueArtifact(data);
await writeJson('outputs/v7-player-value.json', output);
await mkdir(resolve('outputs'), { recursive: true });
await writeFile('outputs/v7-player-value-artifact.json', `${JSON.stringify(artifact, null, 2)}\n`, 'utf8');
await writeFile(
  'lib/v7-player-value-artifact.ts',
  `// Generated by pnpm player:value. Research-only; never a production adjustment.\nexport const V7_PLAYER_VALUE_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;\n`,
);
console.log('V7 player-value research artifact completed.');
console.log(`Qualified production leaders: ${output.top50ProductionLeaders.length}`);
console.log('Availability adjustments: 0 (no timestamped pre-kickoff source).');
console.log('Wrote outputs/v7-player-value.json');
