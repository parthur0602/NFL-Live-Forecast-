import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildV7ProspectiveArtifact, loadResearchData } from './v7-intelligence-core.mjs';

const artifact = buildV7ProspectiveArtifact(await loadResearchData());
await mkdir(resolve('outputs'), { recursive: true });
await writeFile('outputs/v7-prospective-artifact.json', `${JSON.stringify(artifact, null, 2)}\n`);
await writeFile(
  'lib/v7-prospective-artifact.ts',
  `// Generated by pnpm v7:artifact. V7 remains shadow-only.\nexport const V7_PROSPECTIVE_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;\n`,
);
console.log('V7 prospective artifact generated.');
console.log(`Training games: ${artifact.trainingGames}`);
console.log(`Artifact hash: ${artifact.artifactHash}`);
